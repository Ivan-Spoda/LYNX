"""Writes src/core/VoiceMatchTables.inc: the SSL E-Channel EQ / filter calibration measured black-box (round 123)."""
import numpy as np, pickle, vm, re, sslmodel as M, sslfilt as F, bqf, an2, sys
out=[]
def fx(t): return t if any(c in t for c in '.en') else t+'.0'
def arr(name, a, fmt='%.7g', per=8, typ='float'):
    a=np.asarray(a).ravel(); s='static constexpr %s %s[%d] = {\n'%(typ,name,len(a))
    for i in range(0,len(a),per): s+='    '+', '.join(fx(fmt%v) for v in a[i:i+per])+',\n'
    out.append(s+'};\n')
G=M.G
for band in ['lf','hf','lmf','hmf']:
    B=M.Band(band); U=band.upper()
    arr('%sLawText'%band, B.T); arr('%sLawLogW'%band, np.log(B.W))
    arr('%sNodeLogW'%band, [B.fx[f] for f in B.F])
    if B.bell:
        arr('%sQv'%band, B.Q)
        A=np.zeros((len(G),len(B.F),len(B.Q),5))
        for gi,g in enumerate(G):
            for fi,f in enumerate(B.F):
                for qi,q in enumerate(B.Q): A[gi,fi,qi]=B.nodes[(g,f,q)][0]
    else:
        A=np.zeros((2,len(G),len(B.F),5))
        for ti,t in enumerate(['Off','On']):
            for gi,g in enumerate(G):
                for fi,f in enumerate(B.F): A[ti,gi,fi]=B.nodes[(t,g,f)][0]
    arr('%sFeat'%band, A, per=5)
# Q text law (21 points, v = 0 .. 1 step 0.05) -- same for LMF / HMF
vq,tq=M.textlaw('HMF Q'); arr('qText', [tq[int(round(i*50))] for i in range(21)])
# HP law: text Hz -> pole (rad/s, analog domain at 48 kHz)
z=np.load(vm.W+'/ir_ssllaw.npz'); keys=[eval(k) for k in z['keys']]; irs=z['irs']; gl=M.gets('ssllaw')
hp={}; lp={}
for k,h,g in zip(keys,irs,gl):
    if k[0]=='HP':
        t=M.num(g); b,a,e=bqf.fit(h[1:],order=3,nfft=65536); r=np.roots(a); s=2*48000*(r-1)/(r+1)
        hp.setdefault(t,[]).append(-np.real(s[np.argmin(abs(s.imag))]))
    if k[0]=='LP':
        t=M.num(g)*1000; b,a,e=bqf.fit(h[1:],order=2,nfft=65536); n,d=an2.analog(b,a); n=n/d[0]; d=d/d[0]
        lp.setdefault(t,[]).append(np.concatenate([n,d[1:]]))
T=sorted(hp); arr('hpText',T); arr('hpW',[np.mean(hp[t]) for t in T])
T=sorted(lp); arr('lpText',T); arr('lpCoef',[np.mean(lp[t],0) for t in T],per=5,fmt='%.9g',typ='double')
hdr='''// Generated by tmp/vm123/py/gentables.py (round 123) from black-box measurements of the official Waves SSL E-Channel
// trial (tools/fxmeasure, 48 kHz, impulse responses at -40 dBFS, dynamics bypassed). Each EQ band's response is one
// biquad; the tables hold its analog-domain coefficients (inverse bilinear at 48 kHz) normalised by a reference
// frequency, on grids of the displayed gain / frequency / Q. Not code or data from the plug-in: measured responses.
// NOLINTBEGIN
'''
open(sys.argv[1],'w').write(hdr+'\n'.join(out)+'// NOLINTEND\n')
print('written', sum(len(x) for x in out))
