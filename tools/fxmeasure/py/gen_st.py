# generates src/core/SoundtoysStates.inc: her Soundtoys states (read black-box in the official trials) -> LYNX params
import csv, math, sys
S='/home/kauan/.claude/jobs/f8789b49/tmp/vm124/st/'; H='/mnt/d/lynx-work/parity135/st/her/'
def fnv(b):
    h=0xcbf29ce484222325
    for c in b: h^=c; h=(h*0x100000001b3)&0xffffffffffffffff
    return h
def payload(fn):
    d=open(S+fn,'rb').read(); i=d.index(b'PRESET =')+8; j=d.index(b';',i); return d[i:j].strip()
def rows(name):
    r=list(csv.DictReader(open(H+name+'.tsv'),delimiter='\t')); return r
def num(s): return float(s.split()[0])
cl=lambda x:max(0.0,min(1.0,x))
out=[]
out.append('// Generated by tools/fxmeasure/py/gen_st.py (round 135) - do not edit by hand.\n// Her Soundtoys states, each loaded into the official trial (black-box: the host API only, the payload is not decoded)\n// and every parameter read back; key = FNV-1a 64 of the PRESET payload, then (LYNX parameter, value) pairs.\n')
def emit(table, entries):
    out.append('const KnownState %s[] = {\n'%table)
    seen=set()
    for h,slots,pairs,note in entries:
        if h in seen: continue
        seen.add(h)
        out.append('    { 0x%016xull, { %s } }, // %d slots: %s\n'%(h, ', '.join('{ %s, %.6ff }'%(p,v) for p,v in pairs), slots, note))
    out.append('};\n')
# Little AlterBoy -> Voice Shift (pitch, formant, link, mode, drive, mix)
e=[]
for r in rows('LittleAlterBoy'):
    m={'Transpose':0.0,'Quantize':0.5,'Robot':1.0}[r['ShiftMode']]
    pairs=[('vs::pitch',cl((num(r['Pitch'])+12)/24)),('vs::formant',cl((num(r['Formant'])+12)/24)),('vs::link',1.0 if r['FormantLink']=='On' else 0.0),('vs::mode',m),('vs::drive',cl(num(r['Drive'])/10)),('vs::mix',cl(num(r['Mix'])/100))]
    e.append((fnv(payload(r['state']+'.bin')),int(r['slots']),pairs,'%s %s/%s drive %s mix %s'%(r['ShiftMode'],r['Pitch'],r['Formant'],r['Drive'],r['Mix'])))
emit('alterBoyStates',sorted(e,key=lambda x:-x[1]))
# Decapitator -> Ember (ember enum indices passed from argv)
I=lambda k:'em::'+k
e=[]
for r in rows('Decapitator'):
    style={'A':1,'E':2,'N':3,'T':4,'P':5}[r['Style']]
    d=num(r['Drive']); lc=num(r['LowCut']); hc=num(r['HighCut']); trim=num(r['OutputTrim'])
    pairs=[(I('voice'),style/5),(I('drive'),cl(3.2*d/36)),(I('punish'),1.0 if r['Punish']=='On' else 0.0),(I('tone'),cl(0.5+num(r['Tone'])/24)),
           (I('wideCuts'),1.0),(I('lowCutWide'),cl(math.log(lc/20)/math.log(50)) if lc>20.5 else 0.0),(I('highCutWide'),cl(math.log(hc/1000)/math.log(20)) if hc<19900 else 1.0),
           (I('mix'),cl(num(r['Mix'])/100)),(I('autoGain'),0.0),(I('output'),cl((trim-2+18)/36)),(I('thump'),1.0 if r['LowThump']=='On' else 0.0),(I('steep'),1.0 if r['HighSlope']=='Steep' else 0.0)]
    e.append((fnv(payload(r['state']+'.bin')),int(r['slots']),pairs,'%s drive %s tone %s HC %s mix %s trim %s'%(r['Style'],r['Drive'],r['Tone'],r['HighCut'],r['Mix'],r['OutputTrim'])))
emit('decapitatorStates',sorted(e,key=lambda x:-x[1]))
# PanMan -> Auto-pan. The source / rhythm / steps / direction are not host parameters: read from the trial's window for
# one state per setting (tmp/parity135 screenshots), keyed here by (rate, width, smoothing)
modes={('3.5600','150.60','1.00'):('lfo',None,None,'Faast Shimmer Pan'),('0.5700','167.40','0.62'):('lfo',None,None,'Pendulum Pan'),
       ('5.5000','138.00','0.04'):('steps',2,'1/4','Hard Bounce (rhythm shape)'),('1.7800','186.30','0.00'):('steps',5,'1/4','5 steps'),
       ('1.7800','37.80','1.00'):('steps',2,'1/4','Minor Movement (rhythm shape)'),('0.2500','210.00','0.00'):('steps',3,'1/4','DynoPan (custom steps)'),
       ('1.7800','210.00','1.00'):('steps',2,'1/2','One Bar Wide (rhythm shape)')}
notes={'1/1':0,'1/2':0.2,'1/4':0.4,'1/8':0.6,'1/16':0.8,'1/32':1.0}
e=[]
for r in rows('PanMan'):
    k=(r['Rate'],r['Width'],r['Smoothing']); src,steps,note,name=modes[k]
    rate=num(r['Rate']); w=num(r['Width']); off=num(r['Offset'])
    pairs=[('1',cl(0.5+0.5*min(1.0,w/180))),('3',cl(0.5+off/180)),('ap::source',0.5 if src=='lfo' else 1.0),('ap::rate',cl(math.log(rate/0.01)/math.log(1000))),('ap::direction',0.0),
           ('ap::smoothing',cl(num(r['Smoothing']))),('ap::inputGain',cl((num(r['InputGain'])+24)/48)),('ap::outputGain',cl((num(r['OutputGain'])+24)/48)),('ap::analogStage',1.0 if r['InOutMode']=='Analog' else 0.0)]
    if steps: pairs+= [('ap::stepsParam',(steps-2)/6),('ap::stepNote',notes[note])]
    e.append((fnv(payload(r['state']+'.bin')),int(r['slots']),pairs,name))
emit('panManStates',sorted(e,key=lambda x:-x[1]))
sys.stdout.write(''.join(out))
